def _parse_environment_flag(name, value, default=False):
    if value is None:
        return default
    normalized = value.strip().lower()
    if normalized in {'1', 'true', 'yes', 'on'}:
        return True
    if normalized in {'0', 'false', 'no', 'off'}:
        return False
    raise ImproperlyConfigured(f'{name} must be set to a boolean value.')


def _environment_flag(name, default=False):
    return _parse_environment_flag(name, os.environ.get(name), default)


def _secret_key(debug, configured_key):
    if configured_key:
        return configured_key
    if debug:
        return secrets.token_urlsafe(50)
    raise ImproperlyConfigured(
        'Set DJANGO_SECRET_KEY when DEBUG is disabled.'
    )


def _allowed_hosts(debug, configured_hosts):
    hosts = [
        host.strip()
        for host in configured_hosts.split(',')
        if host.strip()
    ]
    if '*' in hosts:
        raise ImproperlyConfigured(
            'DJANGO_ALLOWED_HOSTS must not contain the wildcard host "*".'
        )
    if hosts:
        return hosts
    if debug:
        return ['localhost', '127.0.0.1', '[::1]']
    raise ImproperlyConfigured(
        'Set DJANGO_ALLOWED_HOSTS when DEBUG is disabled.'
    )


def _non_negative_integer(name, value, default):
    if value is None:
        return default
    try:
        parsed = int(value)
    except ValueError as error:
        raise ImproperlyConfigured(f'{name} must be a non-negative integer.') from error
    if parsed < 0:
        raise ImproperlyConfigured(f'{name} must be a non-negative integer.')
    return parsed


def _email_credential(environment, name, legacy_name):
    return environment.get(name) or environment.get(legacy_name) or None


def _email_mailer(debug, environment):
    console_backend = 'django.core.mail.backends.console.EmailBackend'
    smtp_backend = 'django.core.mail.backends.smtp.EmailBackend'
    backend = environment.get(
        'DJANGO_EMAIL_BACKEND',
        console_backend if debug else smtp_backend,
    )
    non_production_backends = {
        console_backend,
        'django.core.mail.backends.dummy.EmailBackend',
        'django.core.mail.backends.filebased.EmailBackend',
        'django.core.mail.backends.locmem.EmailBackend',
    }
    if not debug and backend in non_production_backends:
        raise ImproperlyConfigured(
            'Configure a production email backend with DJANGO_EMAIL_BACKEND.'
        )

    options = {}
    if backend == smtp_backend:
        host = environment.get('DJANGO_EMAIL_HOST', '').strip()
        if not host:
            raise ImproperlyConfigured(
                'Set DJANGO_EMAIL_HOST to configure SMTP email.'
            )
        use_tls = _parse_environment_flag(
            'DJANGO_EMAIL_USE_TLS',
            environment.get('DJANGO_EMAIL_USE_TLS'),
            default=not debug,
        )
        use_ssl = _parse_environment_flag(
            'DJANGO_EMAIL_USE_SSL',
            environment.get('DJANGO_EMAIL_USE_SSL'),
            default=False,
        )
        if use_tls and use_ssl:
            raise ImproperlyConfigured(
                'DJANGO_EMAIL_USE_TLS and DJANGO_EMAIL_USE_SSL cannot both be enabled.'
            )
        port_default = 465 if use_ssl else 587 if use_tls else 25
        port = _non_negative_integer(
            'DJANGO_EMAIL_PORT',
            environment.get('DJANGO_EMAIL_PORT'),
            port_default,
        )
        if port == 0:
            raise ImproperlyConfigured('DJANGO_EMAIL_PORT must be greater than zero.')
        timeout = _non_negative_integer(
            'DJANGO_EMAIL_TIMEOUT',
            environment.get('DJANGO_EMAIL_TIMEOUT'),
            10,
        )
        options = {
            'host': host,
            'port': port,
            'username': _email_credential(
                environment,
                'DJANGO_EMAIL_HOST_USER',
                'DJANGO_EMAIL_USER',
            ),
            'password': _email_credential(
                environment,
                'DJANGO_EMAIL_HOST_PASSWORD',
                'DJANGO_EMAIL_PASSWORD',
            ),
            'use_tls': use_tls,
            'use_ssl': use_ssl,
            'timeout': timeout,
        }
    return {'BACKEND': backend, 'OPTIONS': options}


def _default_from_email(debug, environment):
    email = environment.get(
        'DJANGO_DEFAULT_FROM_EMAIL',
        'webmaster@localhost' if debug else '',
    ).strip()
    if not email:
        raise ImproperlyConfigured(
            'Set DJANGO_DEFAULT_FROM_EMAIL when DEBUG is disabled.'
        )
    return email


def _trusted_proxy_ssl_header(environment):
    if _parse_environment_flag(
        'DJANGO_TRUST_X_FORWARDED_PROTO',
        environment.get('DJANGO_TRUST_X_FORWARDED_PROTO'),
    ):
        return ('HTTP_X_FORWARDED_PROTO', 'https')
    return None


